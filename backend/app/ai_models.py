DEFAULT_MODEL = "seedance"
VALID_MODELS = frozenset(AI_MODELS)

# Smallest max_clip_sec across every model. A project segmented at this cap can
# be run on ANY model without a segment being skipped — the historical default,
# and what VideoProject.max_segment_sec=NULL falls back to.
UNIVERSAL_MAX_SEGMENT_SEC = min(s.max_clip_sec for s in AI_MODELS.values())

# Largest max_clip_sec across every model — the ceiling the project setting and
# its API validation accept.
ABSOLUTE_MAX_SEGMENT_SEC = max(s.max_clip_sec for s in AI_MODELS.values())


def spec_for(model: Optional[str]) -> AIModelSpec:
    """Return the spec for *model*, falling back to the default backend.

    The fallback keeps callers safe against a NULL/unknown value on a row that
    predates a model being added.
    """
    return AI_MODELS.get(model or "", AI_MODELS[DEFAULT_MODEL])


def label_for(model: Optional[str]) -> str:
    """Human-readable label for a model key (used by templates)."""
    return AI_MODELS[model].label if model in AI_MODELS else (model or "")


def kie_model_id(model: Optional[str]) -> str:
    """kie.ai createTask model id for *model*."""
    return spec_for(model).kie_model_id


def is_omni(model: Optional[str]) -> bool:
    """True when *model* uses the Gemini Omni request shape."""
    return spec_for(model).family == "omni"


def resolutions_for(model: Optional[str]) -> tuple[str, ...]:
    """Allowed resolutions for *model*, in display order."""
    return spec_for(model).resolutions


def resolution_or_default(model: Optional[str], resolution: Optional[str]) -> str:
    """Return *resolution* if this model supports it, else the closest tier.

    This is the guard for "the run asks for something this backend cannot do"
    (e.g. a 1080p run submitted to Seedance 2.5, which stops at 720p):

    * exact match → pass it straight through;
    * otherwise the HIGHEST supported tier that does not exceed the request —
      the closest thing to what was asked for without over-spending;
    * otherwise (the request is below everything this model offers, or is
      NULL/unrecognised) the model's LOWEST tier. There is no non-exceeding
      candidate, so the minimum upgrade is the only defensible pick — jumping
      to the model's top tier would turn a stray value into a 4k bill on
      Gemini Omni, whose cheapest option is 720p.

    Ranked via :data:`_RESOLUTION_RANK`, not by tuple position: display order
    happens to be ascending today, and a positional ``resolutions[0]`` would
    silently downgrade a 1080p production run to Seedance 2.5's 480p.
    """
    spec = spec_for(model)
    if resolution in spec.resolutions:
        return resolution  # type: ignore[return-value]
    ranked = sorted(spec.resolutions, key=_resolution_rank)
    want = _RESOLUTION_RANK.get(resolution or "")
    if want is not None:
        not_exceeding = [r for r in ranked if _resolution_rank(r) <= want]
        if not_exceeding:
            return not_exceeding[-1]
    return ranked[0]


def max_clip_sec(model: Optional[str]) -> float:
    """Hard per-clip ceiling (seconds) for *model*."""
    return spec_for(model).max_clip_sec


def min_clip_sec(model: Optional[str]) -> float:
    """Shortest reference clip *model* accepts; swap clips are padded up to it."""
    return spec_for(model).min_clip_sec


# Sentinel duration meaning "match the input video". Not a length — do not clamp
# or compare it against min/max_duration_sec.
FOLLOW_INPUT_DURATION = -1


def duration_for(model: Optional[str], start: float, end: float) -> int:
    """Derive the output duration to request for a clip.

    Three behaviours, by model:
      * ``follows_input_geometry`` (Seedance 2.5) → :data:`FOLLOW_INPUT_DURATION`
        (-1). The model takes the output length from the input video and rejects
        any concrete value; this is also more accurate than we could be, since
        the output then matches the clip exactly instead of a rounded second.
      * fixed duration set (Gemini Omni) → snapped to the nearest allowed value.
      * otherwise → rounded and clamped into the model's supported range.
    """
    spec = spec_for(model)
    if spec.follows_input_geometry:
        return FOLLOW_INPUT_DURATION
    raw = end - start
    if spec.allowed_durations:
        return min(spec.allowed_durations, key=lambda d: abs(d - raw))
    return max(spec.min_duration_sec, min(spec.max_duration_sec, int(round(raw))))


def aspect_for(model: Optional[str], raw: Optional[str]) -> str:
    """Aspect ratio to send for *model*, given the source's ratio *raw*.

    A model that takes its geometry from the input video requires the literal
    ``"adaptive"`` and rejects anything else — including a ratio that happens to
    match the source. Everything else passes *raw* through when Seedance accepts
    it, falling back to ``"adaptive"``.
    """
    if spec_for(model).follows_input_geometry:
        return "adaptive"
    return raw if raw in SEEDANCE_ASPECTS else "adaptive"


def validate_duration(model: Optional[str], duration: int) -> None:
    """Raise ``ValueError`` if *duration* is not requestable for *model*."""
    spec = spec_for(model)
    if spec.follows_input_geometry:
        # -1 is the only legal value: the model derives length from the input.
        if duration != FOLLOW_INPUT_DURATION:
            raise ValueError(
                f"duration must be {FOLLOW_INPUT_DURATION} for {spec.key} "
                f"(it takes the output length from the input video), "
                f"got {duration}"
            )
        return
    if spec.allowed_durations:
        if duration not in spec.allowed_durations:
            raise ValueError(
                f"duration must be one of {spec.allowed_durations} for "
                f"{spec.key}, got {duration}"
            )
        return
    if not (spec.min_duration_sec <= duration <= spec.max_duration_sec):
        raise ValueError(
            f"duration must be between {spec.min_duration_sec} and "
            f"{spec.max_duration_sec} inclusive for {spec.key}, got {duration}"
        )


def models_supporting_segment_len(seconds: float) -> list[str]:
    """Keys of every model that can generate a clip of *seconds* length."""
    return [k for k, s in AI_MODELS.items() if s.max_clip_sec + 0.05 >= seconds]


def models_excluded_by_segment_len(seconds: float) -> list[str]:
    """Keys of every model that CANNOT generate a clip of *seconds* length."""
    return [k for k, s in AI_MODELS.items() if s.max_clip_sec + 0.05 < seconds]


def resolution_choices_json() -> str:
    """JSON ``{model: [[value, label], ...]}`` for the New Run form's JS.

    Serialised once and injected into the template so the client-side
    resolution dropdown is rebuilt from this table rather than a hand-kept copy.
    """
    return json.dumps(
        {
            key: [[r, _RESOLUTION_LABELS.get(r, r)] for r in spec.resolutions]
            for key, spec in AI_MODELS.items()
        }
    )


def model_limits_json() -> str:
    """JSON ``{model: {max_clip_sec, produces_audio, label}}`` for the form's JS.

    Powers the client-side "these swap segments are too long for the selected
    model" warning and the audio-control locking, without hardcoding either
    model's limits in the template.
    """
    return json.dumps(
        {
            key: {
                "max_clip_sec": spec.max_clip_sec,
                "produces_audio": spec.produces_audio,
                "label": spec.label,
            }
            for key, spec in AI_MODELS.items()
        }
    )


