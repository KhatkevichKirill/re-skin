"""
AI model registry — the per-model capability table for swap generation.

A ``Run.model`` value names one entry here. Everything that varies between the
generation backends lives in this module: the kie.ai model id, which
resolutions are offered, how long a clip may be, how the output duration is
derived, and whether the model exposes an explicit audio switch.

Why a registry: before this module the same five facts about each model were
restated in eight places (the ``run_model_enum``, ``_SEEDANCE_KIE_MODEL`` in
pipeline_v2, ``_VALID_MODELS`` + ``_MODEL_RESOLUTIONS`` in api_v2,
``_MODEL_LABELS`` in web_v2, the New Run ``<select>``, a ``MODEL_RESOLUTIONS``
JS map, and a ternary in run_detail.html). Adding a model meant finding all
eight. Now they all read from here, and the template layer gets the JS maps
serialised from :func:`resolution_choices_json` / :func:`model_limits_json`.

Keep this module free of app imports so api_v2, web_v2, kie_client and
pipeline_v2 can all depend on it, and treat it as the single source of truth for
the enum's valid values (mirrored by the ``run_model_enum`` Postgres type — see
migrations e5a1c7d2f3b6, b4f6d8e0c357 and c8d2f4a6e971).

Note the v1 pipeline (``app/pipeline.py``) still carries its own Seedance/Omni
constants. It is frozen and single-model, so it is deliberately left alone; only
the v2 path reads this registry.

Adding a model
--------------
1. Add an :class:`AIModelSpec` to :data:`AI_MODELS`.
2. Add the key to ``run_model_enum`` with an ``ALTER TYPE ... ADD VALUE``
   migration (Postgres enum values can never be removed — pick the name once).
That is the whole change; every v2 call site is driven off this table.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Optional


@dataclass(frozen=True)
class AIModelSpec:
    """Capabilities of one generation backend."""

    # Value stored in runs.model (the run_model_enum label).
    key: str
    # Human-readable name, shown wherever a run's model is displayed.
    label: str
    # kie.ai createTask "model" field. Seedance variants share one request
    # schema and differ only by this id; Gemini Omni has its own payload shape
    # (see KieClient.create_omni_task) and is flagged by `family`.
    kie_model_id: str
    # Which request builder the pipeline must use: "seedance" | "omni".
    family: str
    # Resolutions offered in the UI and accepted by the API, in display order.
    # A run asking for one that is absent is coerced by resolution_or_default,
    # which picks the closest supported tier rather than a positional entry.
    resolutions: tuple[str, ...]
    # Hard ceiling (seconds) on BOTH the reference clip we upload and the
    # output duration we request. Drives segmentation caps and submit-time
    # trimming — a swap segment longer than this cannot be generated by this
    # model, so it is marked failed at submit time with RunSegment
    # .source_fallback set. Because that failure is deterministic — no number of
    # retries makes the segment generatable on this model — the completeness gate
    # lets the run through and the stitch substitutes the ORIGINAL footage for
    # that segment. The run completes and delivers, but part of the video is
    # un-swapped, which the run UI and Run.source_fallback_segments both flag.
    # (Transient failures still block the run; see _skip_segment.)
    max_clip_sec: float
    # Shortest reference clip the model will accept. Swap clips are padded up to
    # this before upload (see _submit_swap_segment_isolated). Seedance 2.0
    # rejects clips under ~1.8s; Seedance 2.5 in video-editing mode requires
    # 4-30s and rejects the whole request below that.
    min_clip_sec: float
    # True when the model derives the output's aspect ratio AND duration from the
    # input video rather than from the request, and REJECTS the request unless we
    # say so explicitly: aspect_ratio must be "adaptive" and duration must be -1.
    #
    # Seedance 2.5 does this whenever it classifies the task as video editing,
    # which it does from the prompt — and every swap submission we make is video
    # editing ("replace the character in the reference video", with a reference
    # video attached), so for 2.5 this is always on. Sending a concrete ratio or
    # duration instead earns:
    #   500 ... `ratio` must be `adaptive`. `duration` must be -1.
    #
    # This is strictly better for us than the alternative: the output then has
    # exactly the input clip's length instead of a rounded whole-second duration,
    # so the per-segment drift the old clamp introduced (a 7.4s clip asking for
    # 7s of output) disappears. Nothing downstream trims the result — clips are
    # concatenated whole — so matching the input exactly is what the stitch wants.
    follows_input_geometry: bool
    # Output-duration bounds sent in the createTask payload. Ignored when
    # follows_input_geometry is set (the duration is -1, not a length).
    min_duration_sec: int
    max_duration_sec: int
    # When set, the model accepts only these exact output durations and the
    # clip length is snapped to the nearest one (Gemini Omni). When None the
    # duration is clamped into [min_duration_sec, max_duration_sec].
    allowed_durations: Optional[tuple[int, ...]]
    # True when createTask accepts a `generate_audio` boolean. Models without it
    # write audio (or not) on their own and reject the field outright.
    supports_generate_audio: bool
    # True when the model produces an audio track at all. Gemini Omni never
    # does, so its runs are forced to audio_mode="original".
    produces_audio: bool
    # One-line description shown next to the model in the New Run form.
    hint: str


# Aspect ratios accepted by the Seedance family.
SEEDANCE_ASPECTS = frozenset({"1:1", "4:3", "16:9", "9:16", "21:9", "adaptive"})

# Every resolution label any model offers, cheapest/smallest first. Needed
# because "which resolution is closest to the one asked for" is an ordering
# question and AIModelSpec.resolutions is a *display* order — the two agree
# today, and resolution_or_default must not depend on them continuing to.
_RESOLUTION_ORDER: tuple[str, ...] = ("480p", "720p", "1080p", "4k")
_RESOLUTION_RANK: dict[str, int] = {r: i for i, r in enumerate(_RESOLUTION_ORDER)}


def _resolution_rank(resolution: str) -> int:
    """Sort key for a resolution label; unknown labels sort lowest.

    A label missing from _RESOLUTION_ORDER means a model was added without
    extending it. Sorting it below everything keeps the fallback conservative
    (cheapest) instead of accidentally promoting it to "highest supported".
    """
    return _RESOLUTION_RANK.get(resolution, -1)


